import type { Tokens } from './tokens';

/** Prefix shared by every CSS custom property emitted by Nasck UI. */
export const CSS_VAR_PREFIX = 'nui';

type TokenTree = { readonly [key: string]: string | TokenTree };

const toKebab = (value: string): string =>
  value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/** Builds the CSS custom property name for a token path, e.g. `['color','bg']` -> `--nui-color-bg`. */
export const cssVarName = (path: readonly string[]): string =>
  `--${[CSS_VAR_PREFIX, ...path.map(toKebab)].join('-')}`;

/** Flattens a nested token tree into `[cssVarName, value]` pairs. */
export const flattenTokens = (
  tree: TokenTree,
  path: readonly string[] = [],
): Array<[string, string]> =>
  Object.entries(tree).flatMap(([key, value]) =>
    typeof value === 'string'
      ? [[cssVarName([...path, key]), value] as [string, string]]
      : flattenTokens(value, [...path, key]),
  );

const declarations = (pairs: Array<[string, string]>, indent: string): string =>
  pairs.map(([name, value]) => `${indent}${name}: ${value};`).join('\n');

const block = (selector: string, body: string): string => `${selector} {\n${body}\n}`;

const themeBlock = (selector: string, scheme: string, colors: TokenTree, indent = '  '): string =>
  `${selector} {\n${indent}color-scheme: ${scheme};\n${declarations(
    flattenTokens(colors, ['color']),
    indent,
  )}\n${indent.slice(2)}}`;

/** Generates the full `tokens.css` stylesheet (themes + reduced motion) from the token tree. */
export const tokensToCss = (source: Tokens): string => {
  const { color, ...scales } = source;
  const reducedMotion = flattenTokens(source.motion.duration, ['motion', 'duration']).map(
    ([name]) => [name, '0ms'] as [string, string],
  );

  return [
    '/* Generated by scripts/build-tokens.ts from src/tokens/tokens.ts. Do not edit by hand. */',
    block(':root', declarations(flattenTokens(scales), '  ')),
    themeBlock(':root,\n[data-theme="light"]', 'light', color.light),
    themeBlock('[data-theme="dark"]', 'dark', color.dark),
    `@media (prefers-color-scheme: dark) {\n${themeBlock(
      '  :root:not([data-theme="light"])',
      'dark',
      color.dark,
      '    ',
    )}\n}`,
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n${declarations(
      reducedMotion,
      '    ',
    )}\n  }\n}`,
    '',
  ].join('\n\n');
};
